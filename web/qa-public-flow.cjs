const path=require('path'),assert=require('node:assert/strict');
const {chromium}=require(path.join(process.env.APPDATA,'npm','node_modules','@playwright','cli','node_modules','playwright'));
(async()=>{
 const base='https://blastlab.45-77-138-147.sslip.io';
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1,acceptDownloads:true,reducedMotion:'reduce'});
 const errors=[];
 page.on('pageerror',e=>errors.push('JS '+e.message));
 const mark=(name,value)=>console.log('WEB_CHAMBER_QA '+name+'='+JSON.stringify(value));
 try{
  await page.goto(base+'/app',{waitUntil:'domcontentloaded',timeout:30000});
  await page.getByText('NOT IMPLEMENTED',{exact:true}).first().waitFor({timeout:30000});
  assert.equal(await page.getByText('NOT IMPLEMENTED',{exact:true}).count(),4);
  mark('LIBRARY',true);
  await page.getByRole('button',{name:/ENTER WEB CHAMBER/}).click();
  await page.waitForURL('**/app/chambers/web');
  await page.getByRole('button',{name:/Low-stock exposure/}).click();
  await page.getByRole('button',{name:/Receipt forgery/}).click();
  assert.equal(await page.getByRole('button',{name:/Low-stock exposure/}).getAttribute('aria-pressed'),'true');
  mark('SELECTED',true);
  await page.getByRole('button',{name:/LAUNCH CONTAINED TEST/}).click();
  mark('RUN_LAUNCHED',true);
  await page.waitForURL(url=>url.pathname==='/app/results'&&url.searchParams.has('run'),{timeout:115000});
  const caseId=new URL(page.url()).searchParams.get('run');
  mark('RESULT_ID',caseId);
  await page.waitForFunction(()=>document.body.innerText.includes('$24.00')&&document.body.innerText.includes('CONTROLLED TEST PASSED'),null,{timeout:30000});
  let text=await page.locator('body').innerText();
  assert.match(text,/\$24\.00/);
  assert.match(text,/SCRIPTED ATTACK FIXTURE/);
  assert.match(text,/BLOCKED PROPOSALS/);
  mark('REPORT_PASS',true);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByText('CONTROLLED TEST PASSED').first().waitFor({timeout:30000});
  assert.equal(new URL(page.url()).searchParams.get('run'),caseId);
  mark('DEEPLINK_RELOAD',true);
  await page.locator('#compare-run').selectOption({index:1});
  await page.waitForTimeout(700);
  assert.match(await page.locator('body').innerText(),/COMPARISON/);
  mark('COMPARE',true);
  const downloadPromise=page.waitForEvent('download',{timeout:12000});
  await page.getByRole('button',{name:/PUBLIC EVIDENCE/}).click();
  const dl=await downloadPromise;
  mark('DOWNLOAD',dl.suggestedFilename());
  await page.getByRole('button',{name:/INSPECT FULL EXECUTION/}).click();
  await page.waitForURL(url=>url.pathname==='/app/control'&&url.searchParams.get('run')===caseId,{timeout:20000});
  await page.getByText('UNTRUSTED WEB SPECIMEN').first().waitFor({timeout:20000});
  mark('CONTROL_REPLAY',true);
  if(errors.length)throw new Error(errors.join(' | '));
  console.log('PUBLIC_UI_COMPLETE_FLOW_PASS');
 }catch(err){console.error('PUBLIC_UI_FLOW_ERROR='+String(err).slice(0,1100));process.exitCode=2}
 await page.close();await browser.close();
})().catch(err=>{console.error(err);process.exitCode=2});
