#!/usr/bin/env bash
set -euo pipefail
index_sha="$1"
og_sha="$2"
proof_sha="$3"
favicon_sha="$4"
root="/var/www/blastlab"
archive="/tmp/phase26-hygiene-v2.tar.gz"
stage="/tmp/phase26-hygiene-v2"
backup="/opt/blastlab/backups/20261107-phase26-hygiene-v2"
test ! -e "$backup"
test -f "$root/index.html" && test -f "$root/og-card.png"
mkdir -p "$stage" "$backup/assets"
tar -xzf "$archive" -C "$stage"
test "$(sha256sum "$stage/index.html" | cut -d ' ' -f1)" = "$index_sha"
test "$(sha256sum "$stage/og-card.png" | cut -d ' ' -f1)" = "$og_sha"
test "$(sha256sum "$stage/proof/evidence.json" | cut -d ' ' -f1)" = "$proof_sha"
test "$(sha256sum "$stage/favicon.svg" | cut -d ' ' -f1)" = "$favicon_sha"
grep -q 'Bring Your Own Agent Security Testing' "$stage/index.html"
grep -q 'og:image:alt' "$stage/index.html"
cp -p "$root/index.html" "$backup/index.html"
cp -p "$root/og-card.png" "$backup/og-card.png"
cp -p "$root/favicon.svg" "$backup/favicon.svg"
cp -a "$root/assets/." "$backup/assets/"
cp -p "$root/proof/evidence.json" "$backup/evidence.json"
rollback(){
 cp -p "$backup/index.html" "$root/index.html"
 cp -p "$backup/og-card.png" "$root/og-card.png"
 cp -p "$backup/favicon.svg" "$root/favicon.svg"
 cp -p "$backup/evidence.json" "$root/proof/evidence.json"
 cp -a "$backup/assets/." "$root/assets/"
 echo "PHASE26_HYGIENE_ROLLBACK_COMPLETE"
}
trap rollback ERR
cp -a "$stage/assets/." "$root/assets/"
install -m 0644 "$stage/og-card.png" "$root/og-card.png"
install -m 0644 "$stage/favicon.svg" "$root/favicon.svg"
install -m 0644 "$stage/proof/evidence.json" "$root/proof/evidence.json"
install -m 0644 "$stage/index.html" "$root/index.html"
test "$(sha256sum "$root/index.html" | cut -d ' ' -f1)" = "$index_sha"
test "$(sha256sum "$root/og-card.png" | cut -d ' ' -f1)" = "$og_sha"
test "$(sha256sum "$root/proof/evidence.json" | cut -d ' ' -f1)" = "$proof_sha"
test "$(sha256sum "$root/favicon.svg" | cut -d ' ' -f1)" = "$favicon_sha"
curl -fsS --max-time 15 "https://blastlab.45-77-138-147.sslip.io/app" | grep -q "Bring Your Own Agent Security Testing"
test "$(curl -fsS --max-time 15 'https://blastlab.45-77-138-147.sslip.io/og-card.png' | sha256sum | cut -d ' ' -f1)" = "$og_sha"
curl -fsS --max-time 15 "https://blastlab.45-77-138-147.sslip.io/proof/evidence.json" | grep -q "FOUR_TECHNICAL_PROOFS_VERIFIED"
curl -fsS --max-time 12 "http://127.0.0.1:8123/api/health" >/dev/null
trap - ERR
echo "PHASE26_PRODUCT_HYGIENE_RELEASE_PASS"
